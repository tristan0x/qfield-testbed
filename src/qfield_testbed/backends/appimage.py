"""The `appimage` backend: a Linux AppImage run on the host with its own XDG directories."""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

from qfield_testbed.backends.qgis_host import _quote


@dataclass(frozen=True)
class AppImageBackend:
    directory: Path
    """Private directory of the component; XDG config/data/cache live under it."""

    @property
    def config_home(self) -> Path:
        return self.directory / "config"

    @property
    def data_home(self) -> Path:
        return self.directory / "data"

    @property
    def cache_home(self) -> Path:
        return self.directory / "cache"

    def ensure(self) -> None:
        for path in (self.config_home, self.data_home, self.cache_home):
            path.mkdir(parents=True, exist_ok=True)

    def env(self) -> dict[str, str]:
        return {
            "XDG_CONFIG_HOME": str(self.config_home),
            "XDG_DATA_HOME": str(self.data_home),
            "XDG_CACHE_HOME": str(self.cache_home),
            # no FUSE needed: the AppImage extracts itself to a temporary directory
            "APPIMAGE_EXTRACT_AND_RUN": "1",
        }

    def launcher_lines(self, appimage: Path, extra_env: dict[str, str] | None = None) -> list[str]:
        env = {**self.env(), **(extra_env or {})}
        return [
            "#!/usr/bin/env bash",
            "# generated by qfield-testbed: QField desktop with this deployment's settings",
            "set -euo pipefail",
            *(f"export {key}={_quote(value)}" for key, value in sorted(env.items())),
            f'exec {_quote(str(appimage))} "$@"',
        ]
