"""The `qgis-docker` backend: a published ``qgis/qgis:<tag>`` image instead of the host QGIS.

The container shares the host network namespace, so the X display (including an SSH-forwarded
``localhost:N.0``) and the deployment's QFieldCloud URL are the same as on the host, and it mounts the home
directory, the testbed home and the cache at their own paths, so the profile, the plugin symlinks and any
worktree resolve identically inside and outside the container.
"""

from __future__ import annotations

import os
import re
from collections.abc import Iterable
from dataclasses import dataclass, field
from pathlib import Path

from qfield_testbed.backends.qgis_host import PROFILE_NAME, _quote
from qfield_testbed.errors import TestbedError
from qfield_testbed.runtimes import docker
from qfield_testbed.runtimes.shell import Runner

_VERSION = re.compile(r"QGIS\s+(\d+\.\d+\.\d+)")
PYQGIS_PATH = "/usr/share/qgis/python"
DERIVED_DOCKERFILE = """\
FROM {base}
# the published image is made for CI: Qt's xcb platform plugin needs libxcb-cursor0 to open a display
RUN apt-get update && apt-get install -y --no-install-recommends libxcb-cursor0 && rm -rf /var/lib/apt/lists/*
"""


def mount_roots(paths: Iterable[Path]) -> list[Path]:
    """Deduplicate paths so that nested ones are covered by their ancestor (one bind mount each)."""
    roots: list[Path] = []
    for path in sorted({p.resolve() for p in paths}, key=lambda p: len(p.parts)):
        if not any(path == root or root in path.parents for root in roots):
            roots.append(path)
    return roots


@dataclass(frozen=True)
class QgisDockerBackend:
    runner: Runner
    tag: str
    mounts: list[Path] = field(default_factory=list)
    """Host directories made available at the same path inside the container (read-write)."""

    @property
    def base_image(self) -> str:
        return f"qgis/qgis:{self.tag}"

    @property
    def image(self) -> str:
        """The base image plus what a desktop session needs (the published image targets CI)."""
        return f"qft-qgis:{self.tag}"

    def pull(self) -> None:
        if docker.image_exists(self.runner, self.image):
            return
        if not docker.image_exists(self.runner, self.base_image):
            self.runner.run(["docker", "pull", "--quiet", self.base_image], timeout=1800)
        dockerfile = DERIVED_DOCKERFILE.format(base=self.base_image)
        self.runner.run(["docker", "build", "--quiet", "-t", self.image, "-"], stdin=dockerfile, timeout=1800)

    def _user_args(self) -> list[str]:
        home = str(Path.home())
        return ["--user", f"{os.getuid()}:{os.getgid()}", "-e", f"HOME={home}"]

    def _mount_args(self) -> list[str]:
        args: list[str] = []
        for root in mount_roots([Path.home(), *self.mounts]):
            args += ["-v", f"{root}:{root}"]
        return args

    def base_command(self, *, interactive: bool) -> list[str]:
        cmd = ["docker", "run", "--rm", "--network", "host", *self._user_args(), *self._mount_args()]
        cmd += ["-e", f"PYTHONPATH={PYQGIS_PATH}"]
        if interactive:
            cmd += ["-it"]
        return cmd

    def version(self) -> str:
        out = self.runner.run(
            [*self.base_command(interactive=False), "-e", "QT_QPA_PLATFORM=offscreen", self.image, "qgis", "--version"],
            check=False,
            timeout=300,
        ).stdout
        match = _VERSION.search(out)
        if not match:
            raise TestbedError(f"cannot read the QGIS version of {self.image}: {out.strip()[:80]!r}")
        return match.group(1)

    def run_python(self, script: Path, *args: str, env: dict[str, str] | None = None, timeout: float = 600) -> str:
        cmd = [*self.base_command(interactive=False), "-e", "QT_QPA_PLATFORM=offscreen"]
        for key, value in (env or {}).items():
            cmd += ["-e", f"{key}={value}"]
        cmd += [self.image, "python3", str(script), *args]
        return self.runner.run(cmd, timeout=timeout).stdout

    def launcher_lines(self, profiles_path: Path, env: dict[str, str]) -> list[str]:
        display_env = {
            "DISPLAY": "${DISPLAY:-}",
            "XAUTHORITY": "${XAUTHORITY:-$HOME/.Xauthority}",
            "QT_QPA_PLATFORM": "${QT_QPA_PLATFORM:-xcb}",  # `offscreen` for headless `--code` runs
            "QT_X11_NO_MITSHM": "1",
            **env,
        }
        cmd = [*self.base_command(interactive=False), "${TTY_FLAGS}", "-v", "/tmp/.X11-unix:/tmp/.X11-unix"]  # noqa: S108
        for key, value in display_env.items():
            cmd += ["-e", f"{key}={value}"]
        cmd += [self.image, "qgis", "--profiles-path", str(profiles_path), "--profile", PROFILE_NAME]
        return [
            "#!/usr/bin/env bash",
            f"# generated by qfield-testbed: QGIS {self.tag} from Docker with this deployment's profile",
            "set -euo pipefail",
            "# a TTY only when there is one (scripts drive QGIS headless with `--code` from a pipe)",
            "TTY_FLAGS=$([ -t 0 ] && echo -it || echo -i)",
            "exec " + " ".join(_shell_token(part) for part in cmd) + ' "$@"',
        ]


_PLAIN = re.compile(r"^[A-Za-z0-9_./:=@%+,-]+$")


def _shell_token(part: str) -> str:
    """Quote only what needs it; keep ``${VAR}`` expansions (double-quoted) so the launcher follows the session."""
    if part == "${TTY_FLAGS}":
        return part  # word-split on purpose: `-it` or `-i`
    if "${" in part:
        return '"' + part.replace('"', '\\"') + '"'
    return part if _PLAIN.match(part) else _quote(part)
