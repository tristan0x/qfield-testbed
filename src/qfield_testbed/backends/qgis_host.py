"""The `qgis-host` backend: the QGIS installed on this machine, with the deployment's own profiles path."""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from qfield_testbed.errors import TestbedError
from qfield_testbed.runtimes.shell import Runner

PROFILE_NAME = "default"
"""The single profile inside a deployment's profiles path (QGIS_CUSTOM_CONFIG_PATH always maps to `default`)."""

_VERSION = re.compile(r"QGIS\s+(\d+\.\d+\.\d+)")
NO_DISPLAY_HINT = (
    "qft: no display: QGIS needs one even with --code; install xvfb (xvfb-run) or use `qgis: {version: docker:<tag>}`"
)


@dataclass(frozen=True)
class QgisHostBackend:
    runner: Runner
    binary: Path

    @classmethod
    def detect(cls, runner: Runner) -> QgisHostBackend:
        found = runner.which("qgis")
        if not found:
            raise TestbedError("no `qgis` executable on PATH; install QGIS or use `qgis: {version: docker:<tag>}`")
        return cls(runner=runner, binary=Path(found).resolve())

    @property
    def prefix(self) -> Path:
        """``/usr`` for ``/usr/bin/qgis``."""
        return self.binary.parent.parent

    @property
    def pyqgis_path(self) -> Path:
        """Where the Python bindings live when they are not on the default ``sys.path`` (Debian: /usr/share/qgis/python)."""
        return self.prefix / "share" / "qgis" / "python"

    @property
    def python(self) -> Path:
        """The system interpreter QGIS was built against (never the testbed's own virtualenv)."""
        return Path("/usr/bin/python3")

    def version(self) -> str:
        out = self.runner.run([str(self.binary), "--version"], check=False).stdout
        match = _VERSION.search(out)
        if not match:
            raise TestbedError(f"cannot read the QGIS version from `{self.binary} --version`: {out.strip()[:80]!r}")
        return match.group(1)

    def python_env(self) -> dict[str, str]:
        return {"PYTHONPATH": str(self.pyqgis_path), "QT_QPA_PLATFORM": "offscreen"}

    def run_python(self, script: Path, *args: str, env: dict[str, str] | None = None, timeout: float = 300) -> str:
        """Run a PyQGIS script headless; returns its stdout, raises CommandError with its stderr tail."""
        merged = {**self.python_env(), **(env or {})}
        return self.runner.run([str(self.python), str(script), *args], env=merged, timeout=timeout).stdout

    def launcher_lines(self, profiles_path: Path, env: dict[str, str]) -> list[str]:
        exports = [f"export {key}={_quote(value)}" for key, value in sorted(env.items())]
        qgis = f'{_quote(str(self.binary))} --profiles-path {_quote(str(profiles_path))} --profile {PROFILE_NAME} "$@"'
        return [
            "#!/usr/bin/env bash",
            "# generated by qfield-testbed: QGIS with this deployment's profile",
            "set -euo pipefail",
            "# a virtualenv of the caller (`uv run qft …`) would replace the system Python QGIS embeds, losing PyQt",
            'if [ -n "${VIRTUAL_ENV:-}" ]; then',
            '  PATH=":$PATH:"; PATH=${PATH//":$VIRTUAL_ENV/bin:"/:}; PATH=${PATH#:}; PATH=${PATH%:}',
            "fi",
            "unset VIRTUAL_ENV PYTHONHOME",
            *exports,
            "# QGIS refuses to start without a display, even with --code: use a virtual one when there is none",
            'if [ -z "${DISPLAY:-}${WAYLAND_DISPLAY:-}" ]; then',
            "  if command -v xvfb-run >/dev/null; then",
            f"    exec xvfb-run -a {qgis}",
            "  fi",
            f"  echo {_quote(NO_DISPLAY_HINT)} >&2",
            "  exit 1",
            "fi",
            f"exec {qgis}",
        ]


def _quote(value: str) -> str:
    return "'" + value.replace("'", "'\\''") + "'"
