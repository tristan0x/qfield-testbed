"""The `qfield-ios` component: QField in the iOS Simulator of a remote macOS host.

Nothing runs locally: a configured `ios_hosts` entry is driven over SSH (`xcrun simctl`), the simulator build of
QField.app is found in a checkout on the Mac, and a reverse SSH tunnel brings the deployment's QFieldCloud to
``http://localhost:<port>/`` inside the simulator.
"""

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any, ClassVar

from qfield_testbed.backends.ios_simulator import IosSimulatorBackend
from qfield_testbed.components import register
from qfield_testbed.components.base import Component
from qfield_testbed.errors import MaterializationUnavailableError, TestbedError
from qfield_testbed.provision import ios_settings
from qfield_testbed.provision.qfield_settings import manual_steps
from qfield_testbed.revisions import Revision
from qfield_testbed.runtimes.ssh import Ssh, process_alive, stop_process
from qfield_testbed.spec import BuildSource, QFieldIosSpec

log = logging.getLogger(__name__)


@register
class QFieldIos(Component):
    name: ClassVar[str] = "qfield-ios"
    spec: QFieldIosSpec

    def ssh(self) -> Ssh:
        host = self.ctx.config.ios_hosts.get(self.spec.host)
        if host is None:
            configured = ", ".join(sorted(self.ctx.config.ios_hosts)) or "none"
            raise TestbedError(
                f"iOS host '{self.spec.host}' is not configured (ios_hosts in {self.ctx.config.__class__.file_path()}); "
                f"configured: {configured}"
            )
        return Ssh(self.ctx.runner, host.ssh)

    def backend(self) -> IosSimulatorBackend:
        return IosSimulatorBackend(ssh=self.ssh(), device_name=self.spec.device, runtime=self.spec.runtime)

    @property
    def simulator_name(self) -> str:
        return f"qft-{self.ctx.name}"

    def check_host(self) -> list[str]:
        try:
            ssh = self.ssh()
        except TestbedError as exc:
            return [str(exc)]
        if self.ctx.runner.which("ssh") is None:
            return ["ssh client missing"]
        if not ssh.reachable():
            return [
                f"iOS host '{self.spec.host}' ({ssh.destination}) unreachable over SSH (BatchMode: keys must be set up)"
            ]
        if not self.backend().available():
            return [f"`xcrun simctl` fails on {ssh.destination}: is Xcode installed and selected (xcode-select)?"]
        return []

    # --- lifecycle --------------------------------------------------------------------------------------

    def resolve(self) -> Revision:
        source = self.spec.version
        if not isinstance(source, BuildSource):
            raise TestbedError(f"unsupported version source for qfield-ios: {source}")
        result = self.ssh().run("git", "-C", str(source.path), "rev-parse", "HEAD", check=False)
        sha = result.stdout.strip() if result.returncode == 0 else None
        dirty = False
        if sha:
            status = self.ssh().run(
                "git", "-C", str(source.path), "status", "--porcelain", "--untracked-files=no", check=False
            )
            dirty = bool(status.stdout.strip())
        label = f"build@{sha[:12]}" if sha else f"build@{source.path.name}"
        return Revision(source=source, label=label, sha=sha, dirty=dirty)

    def materialize(self, revision: Revision) -> Path:
        """The simulator ``QField.app`` on the Mac (remote path), found under the build directory."""
        assert isinstance(revision.source, BuildSource)  # noqa: S101
        result = self.ssh().run(
            "find",
            str(revision.source.path),
            "-maxdepth",
            "6",
            "-name",
            "QField.app",
            "-path",
            "*iphonesimulator*",
            check=False,
        )
        apps = [line.strip() for line in result.stdout.splitlines() if line.strip()]
        if not apps:
            result = self.ssh().run(
                "find", str(revision.source.path), "-maxdepth", "6", "-name", "QField.app", check=False
            )
            apps = [line.strip() for line in result.stdout.splitlines() if line.strip()]
        if not apps:
            raise MaterializationUnavailableError(
                f"no QField.app under {revision.source.path} on the Mac; build QField for the simulator there first"
            )
        return Path(min(apps))

    def render(self, revision: Revision, materialized: Path) -> None:
        launcher = self.ctx.directory / "bin" / "ios"
        launcher.parent.mkdir(parents=True, exist_ok=True)
        ssh = self.ssh()
        launcher.write_text(
            "#!/usr/bin/env bash\n# generated by qfield-testbed: show the simulator on the Mac\n"
            f"exec ssh {ssh.destination} -- open -a Simulator\n"
        )
        launcher.chmod(0o755)
        self.state.facts.update(
            {
                "app": str(materialized),
                "host": ssh.destination,
                "launcher": str(launcher),
                "revision_label": revision.label,
            }
        )

    def start(self) -> None:
        backend = self.backend()
        device = backend.ensure_device(self.simulator_name)
        log.info("booting simulator %s (%s)", device.name, device.udid)
        backend.boot(device.udid)
        backend.install(device.udid, self.state.facts["app"])
        self.state.facts["udid"] = device.udid
        self.state.facts["runtime"] = device.runtime
        port = self.ctx.ports.port("app")
        if not process_alive(self.state.facts.get("tunnel_pid")):
            self.state.facts["tunnel_pid"] = self.ssh().reverse_tunnel(port, port)
        self.state.facts["qfieldcloud_url"] = f"http://localhost:{port}/"

    def wire(self) -> None:
        credentials = self.ctx.state.credentials
        udid = self.state.facts.get("udid")
        if credentials is None or not udid:
            return
        url = self.state.facts["qfieldcloud_url"]
        plist = ios_settings.seed_qfield_settings(self.ssh(), self.backend(), udid, url, credentials.username)
        self.state.facts["settings_file"] = plist
        if plist is None:
            log.warning("%s", manual_steps(url, credentials.username))

    def stop(self) -> None:
        if udid := self.state.facts.get("udid"):
            self.backend().shutdown(udid)
        stop_process(self.state.facts.pop("tunnel_pid", None))

    def reset(self) -> None:
        self.stop()
        if udid := self.state.facts.pop("udid", None):
            self.backend().delete(udid)

    def remove(self) -> None:
        try:
            self.reset()
        except TestbedError as exc:  # the Mac may be gone; the deployment must still be removable
            log.warning("could not clean the simulator: %s", exc)

    def describe(self) -> dict[str, Any]:
        facts = self.state.facts
        return {
            "host": facts.get("host"),
            "udid": facts.get("udid"),
            "device": self.spec.device,
            "runtime": facts.get("runtime"),
            "app": facts.get("app"),
            "qfieldcloud_url": facts.get("qfieldcloud_url"),
            "settings_file": facts.get("settings_file"),
            "launcher": facts.get("launcher"),
        }
